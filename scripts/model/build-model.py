"""Turn the exported head, jaw and crest (model.json, written by the
Blender export script) into src/robot/model.ts: positions as Int16 and
normals as Int8, base64 encoded, with each triangle's material.

The source sculpt is a 3D print, so its parts are hollow shells: faces on
the inside of a shell (facing back toward the part's middle) are marked
as the dark inside, which shows only through the mouth and from below."""

import base64, json, sys
import numpy as np

src, dst = sys.argv[1], sys.argv[2]
m = json.load(open(src))
Q = 16384  # position units per head unit (±2 head units fit an Int16)

def b64(a):
    return base64.b64encode(a.tobytes()).decode()

def smooth_normals(v, t, n, crease=38):
    """Each triangle's shading normal: the mean of its corners' normals, each
    corner averaging the triangles round it that bend less than `crease`
    degrees from this one. Decimated triangles are irregular, so flat
    normals shade blotchy; this keeps the curves smooth and the creases
    (the slot, the jaw's edges) sharp."""
    a, b, cc = v[t[:, 0]], v[t[:, 1]], v[t[:, 2]]
    area = np.linalg.norm(np.cross(b - a, cc - a), axis=1)[:, None] / 2
    around = [[] for _ in range(len(v))]
    for f, tri in enumerate(t):
        for k in tri:
            around[k].append(f)
    cos = np.cos(np.radians(crease))
    out = np.zeros_like(n)
    for f, tri in enumerate(t):
        acc = np.zeros(3)
        for k in tri:
            nb = np.array(around[k])
            near = nb[(n[nb] @ n[f]) > cos]
            m = (n[near] * area[near]).sum(axis=0)
            acc += m / (np.linalg.norm(m) or 1)
        out[f] = acc / (np.linalg.norm(acc) or 1)
    return out

out = []
for name, key, axis in [('head', 'head', 'head'), ('jaw', 'chin', 'jaw'), ('crest', 'head-fin', None)]:
    p = m['parts'][key]
    v = np.array(p['v'], dtype=np.float64)
    t = np.array(p['t'], dtype=np.int64)
    n = np.array(p['n'], dtype=np.float64)
    c = v[t].mean(axis=1)
    n = smooth_normals(v, t, n)
    mats = np.zeros(len(t), dtype=np.uint8)
    if axis == 'head':
        # the middle of the cranium at each height
        mid = np.stack([np.zeros(len(c)), np.clip(c[:, 1], -0.42, -0.08), np.zeros(len(c))], axis=1)
        mats[((c - mid) * n).sum(axis=1) < 0] = 2
        # the flat ring round the bottom of the shell faces straight down: inside too
        mats[(n[:, 1] > 0.9) & (c[:, 1] > -0.02)] = 2
    elif axis == 'jaw':
        # a face looking toward the middle of the bucket is inside it (its
        # walls and floor, which show through an open mouth); a face looking
        # away from it is outside
        lo, hi = v[:, 1].min(), v[:, 1].max()
        zc = (v[:, 2].min() + v[:, 2].max()) / 2
        mid = np.array([0, lo + (hi - lo) * 0.45, zc])
        mats[((mid - c) * n).sum(axis=1) > 0.002] = 2
    if name == 'crest':
        mats[:] = 1
    pos = np.round(v * Q).astype(np.int16)
    nrm = np.round(n * 127).astype(np.int8)
    out.append(f"  {name}: {{ pos: '{b64(pos)}', tri: '{b64(t.astype(np.uint16))}', nrm: '{b64(nrm)}', mat: '{b64(mats)}' }},")
    print(name, len(v), 'verts', len(t), 'tris', int((mats == 2).sum()), 'inside')

eyes = m['eyes']
hinge = m['hinge']
ts = f"""/* Generated by scripts/model/build-model.py from a decimated sculpt; do not edit.
   Source: a sculpt by ChelsCCT (Chelsey Creates Things),
   https://www.printables.com/model/13478, licensed CC BY 4.0
   (https://creativecommons.org/licenses/by/4.0/). Adapted: parts
   assembled, decimated, rescaled and re-oriented. */

export const MODEL_Q = {Q};

export const MODEL = {{
{chr(10).join(out)}
}};

/** The jaw's hinge, [y, z] in head units. */
export const MODEL_HINGE: [number, number] = [{hinge[0]:.5f}, {hinge[1]:.5f}];

/** Each eye's centre on the face and its socket's radius, in head units (left of screen first). */
export const MODEL_EYES: Array<[number, number, number, number]> = [{', '.join(f'[{e["c"][0]:.5f}, {e["c"][1]:.5f}, {e["c"][2]:.5f}, {e["r"]:.5f}]' for e in eyes)}];
"""
open(dst, 'w').write(ts)
print('wrote', dst, len(ts), 'bytes')
