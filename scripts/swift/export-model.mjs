/* Writes the head model for the Swift package from the TS one, so both
   draw the same bytes: Sources/IronGiant/Model/ModelData.swift.

   node scripts/swift/export-model.mjs   (Node 22.18+ reads the .ts directly) */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as m from '../../src/robot/model.ts';

const out = fileURLToPath(new URL('../../Sources/IronGiant/Model/ModelData.swift', import.meta.url));

const num = (x) => {
  const s = String(x);
  return s.includes('.') || s.includes('e') ? s : `${s}.0`;
};
const part = (name, p) =>
  `        ${name}: Part(\n` +
  ['pos', 'tri', 'nrm', 'mat'].map((k) => `            ${k}: "${p[k]}"`).join(',\n') +
  `\n        )`;
const model = (name, doc, src) =>
  `    /// ${doc}\n    static let ${name} = Model(\n` +
  ['head', 'jaw', 'crest'].map((k) => part(k, src[k])).join(',\n') +
  `\n    )\n`;

const swift = `// Generated by scripts/swift/export-model.mjs from src/robot/model.ts; do not edit.
//
// Source: the head of a robot sculpt by EMA Labs, https://www.printables.com/model/212558,
// licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Adapted: re-oriented,
// rescaled, cut into cranium and jaw, neck removed, decimated.

enum ModelData {
    /// One part of the sculpt, base64: int16 positions over \`q\`, uint16 triangles,
    /// int8 per-triangle normals, a material per triangle.
    struct Part: Sendable {
        let pos: String
        let tri: String
        let nrm: String
        let mat: String
    }

    struct Model: Sendable {
        let head: Part
        let jaw: Part
        let crest: Part
    }

    static let q: Float = ${num(m.MODEL_Q)}

${model('full', 'The head at full detail.', m.MODEL)}
${model('low', 'The same head with fewer triangles, for small sizes.', m.MODEL_LOW)}
    /// The jaw's hinge, [y, z] in head units.
    static let hinge: SIMD2<Float> = [${m.MODEL_HINGE.map(num).join(', ')}]

    /// The cranium's radius round its middle at heights from the mouth line up, [y, r].
    static let profile: [SIMD2<Float>] = [${m.MODEL_PROFILE.map((p) => `[${p.map(num).join(', ')}]`).join(', ')}]

    /// The head's reach at rest: the top of the crest, the bottom of the jaw, the widest side.
    static let bounds: SIMD3<Float> = [${m.MODEL_BOUNDS.map(num).join(', ')}]

    /// Each eye's centre on the face and its socket's radius, in head units (left of screen first).
    static let eyes: [SIMD4<Float>] = [${m.MODEL_EYES.map((e) => `[${e.map(num).join(', ')}]`).join(', ')}]
}
`;

writeFileSync(out, swift);
console.log(`wrote ${out} (${swift.length} bytes)`);
